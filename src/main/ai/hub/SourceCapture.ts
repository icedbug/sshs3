import crypto from "node:crypto";
import type { AgentToolRecord } from "../../../shared/types/aiHub";
import type { AnswerSource, AnswerSourceCall, StoredSourceSpan } from "../../../shared/answerSources";
import { maskContext } from "./privacy";

type Descriptor = Omit<AnswerSource, "ref" | "digest" | "excerpt" | "excerptTruncated">;
type Row = Record<string, unknown>;
const row = (v: unknown): Row => v && typeof v === "object" && !Array.isArray(v) ? v as Row : {};
const str = (v: unknown) => typeof v === "string" ? v : "";
const num = (v: unknown) => typeof v === "number" && Number.isFinite(v) ? v : undefined;
const hash = (text: string) => crypto.createHash("sha256").update(text).digest("hex");
const map = (v: unknown, fn: (r: Row) => unknown) => Array.isArray(v) ? v.map(x => fn(row(x))) : v;

export const KB_INDEX_SOURCES = Symbol("KB index entries selected for the model");
export interface IndexSource { id: string; title: string; revision: number; updatedAt: number; line: string }
type Source = { descriptor: Descriptor; text: string; ref: string; legacy: boolean };
const MARKER = /⟦[a-f0-9]{12}:(\d+)([+-])⟧/g;
/**
 * The tools whose results are sources: what they return can be cited ([S1]) and can back an
 * observation that confirms a cause. Everything an agent reads a system with is among them, not
 * only its own terminal: a command across a cluster, a file, a diff, an investigator's report.
 */
const SOURCE_TOOLS = new Set([
  "workspace_context", "sshs3_kb_search", "terminal_command", "terminal_verify", "sshs3_change",
  "sshs3_cluster_exec", "sshs3_storage_ops", "file_read", "sshs3_investigate",
]);

/** Private delimiters survive serialization and clipping. They are removed at the transport boundary.
 * Only a delimiter generated by this runtime and surviving in the submitted body can select a receipt. */
export class SourceCapture {
  private readonly nonce = crypto.randomBytes(6).toString("hex");
  private readonly entries: Source[] = [];
  private readonly sourceIds = new Map<string, number>();

  constructor(private readonly clean: (s: string) => string) {}

  private mark(text: string, d: Descriptor, legacy = false): string {
    if (!text.trim() || !d.id || !text.replace(/<\/?untrusted_data\b[^>]*>/g, "").trim()) return text;
    const clean = this.clean(text);
    const key = JSON.stringify([d.kind, d.id, d.revision, d.updatedAt, d.observedAt, d.indexOnly, d.attachment, legacy, hash(clean)]);
    let n = this.sourceIds.get(key);
    if (n === undefined) {
      n = this.entries.length;
      this.sourceIds.set(key, n);
      this.entries.push({ descriptor: { ...d, id: maskContext(this.clean(d.id)).slice(0, 200), label: maskContext(this.clean(d.label)).slice(0, 180) }, text: clean, legacy, ref: "S" + (n + 1) });
    }
    return `⟦${this.nonce}:${n}+⟧${text}⟦${this.nonce}:${n}-⟧`;
  }

  page(r: Row, text: string, indexOnly = false): string {
    return this.mark(text, { kind: "kb-page", id: str(r.id || r.page), label: str(r.title), revision: num(r.revision), updatedAt: num(r.updatedAt), ...(indexOnly && { indexOnly: true }) });
  }
  doc(r: Row, text: string, indexOnly = false): string {
    return this.mark(text, { kind: "kb-document", id: str(r.docId || r.id), label: str(r.title), revision: num(row(r.external).version ?? r.revision), updatedAt: num(r.updatedAt), ...(indexOnly && { indexOnly: true }) });
  }
  memory(r: Row, text: string): string {
    return this.mark(text, { kind: "memory", id: str(r.id), label: str(r.title), updatedAt: num(r.updatedAt) });
  }
  private terminal(r: Row, text: string, at?: number, attachment = false): string {
    // One terminal, one id: an attachment names it "terminal:<id>", a command's output "<id>". Two ids
    // listed one terminal twice among an answer's sources, as if there were two.
    const id = str(r.id).replace(/^terminal:/, "");
    return this.mark(text, { kind: "terminal", id, label: str(r.label || id), observedAt: at, ...(attachment && { attachment: true }) });
  }

  indexText(text: string, value: object): string {
    const ctx = value as { [KB_INDEX_SOURCES]?: IndexSource[] };
    const index = new Map(ctx[KB_INDEX_SOURCES]?.map(p => [p.line, p]));
    return index.size ? text.split("\n").map(line => {
      const p = index.get(line);
      return p ? this.page({ ...p }, line, true) : line;
    }).join("\n") : text;
  }

  /** A copy of the already-selected context, with annotations on source content only. */
  context(value: unknown): unknown {
    if (!value || typeof value !== "object" || Array.isArray(value)) return value;
    const ctx = value as Row & { [KB_INDEX_SOURCES]?: IndexSource[] };
    const out = { ...ctx };
    if (typeof ctx.kbPageIndex === "string") out.kbPageIndex = this.indexText(ctx.kbPageIndex, ctx);
    const reading = row(ctx.targetLastReading);
    const readAt = Date.parse(str(reading.readAt));
    if (str(reading.serverId) && Number.isFinite(readAt) && Array.isArray(reading.lines)) {
      const descriptor: Descriptor = { kind: "server-reading", id: str(reading.serverId), label: str(reading.serverName), observedAt: readAt };
      const lines = reading.lines.map(line => typeof line === "string" ? this.mark(line, descriptor) : line);
      // The spotlight block repeats these rows. Only match whole rows inside that block.
      const originals = new Set(reading.lines);
      const spotlighted = str(reading.spotlighted).split("\n").map((line, i, all) =>
        i > 0 && i < all.length - 1 && originals.has(line) ? this.mark(line, descriptor) : line,
      ).join("\n");
      out.targetLastReading = { ...reading, lines, ...(typeof reading.spotlighted === "string" && { spotlighted }) };
    }
    const at = num(ctx.observedAt);
    const target = row(ctx.target);
    if (typeof target.output === "string") out.target = { ...target, output: this.terminal(row(target.session), target.output, at) };
    if (ctx.terminals) out.terminals = map(ctx.terminals, r => typeof r.recentOutput === "string" && !r.recentOutput.startsWith("(the target's:") ? { ...r, recentOutput: this.terminal(r, r.recentOutput, at) } : r);
    for (const field of ["attachments", "history"]) if (ctx[field]) out[field] = map(ctx[field], r => {
      const text = str(r.text);
      return r.kind === "terminal" || str(r.id).startsWith("terminal:") ? { ...r, text: this.terminal(r, text, num(r.observedAt), field === "attachments") } : r;
    });
    const memory = (r: Row) => typeof r.text === "string" ? { ...r, text: this.memory(r, r.text) } : r;
    for (const field of ["coreMemories", "workspaceMemories"]) if (Array.isArray(ctx[field])) out[field] = map(ctx[field], memory);
    if (ctx.memoryTiers && typeof ctx.memoryTiers === "object") out.memoryTiers = Object.fromEntries(Object.entries(row(ctx.memoryTiers)).map(([k,v]) => [k, map(v, memory)]));
    if (Array.isArray(ctx.kbDocuments)) out.kbDocuments = map(ctx.kbDocuments, r => ({ ...r, title: this.doc(r, str(r.title), true) }));
    if (Array.isArray(ctx.kbBoundPages)) out.kbBoundPages = map(ctx.kbBoundPages, r => ({ ...r, body: this.page(r, str(r.body)) }));
    if (Array.isArray(ctx.kbBoundDocuments)) out.kbBoundDocuments = map(ctx.kbBoundDocuments, r => ({ ...r, content: this.doc(r, str(r.content)) }));
    return out;
  }

  tool(name: string, value: unknown, target?: { sessionId: string; label: string }, at?: number): unknown {
    const r = row(value);
    if (name === "workspace_context") return this.context(value);
    if (name === "sshs3_kb_search") {
      if (typeof r.body === "string" && r.page) return { ...r, body: this.page(r, r.body) };
      if (Array.isArray(r.sections)) return { ...r, sections: map(r.sections, s => ({ ...s, text: this.doc(r, str(s.text)) })) };
      if (Array.isArray(r.pages) || Array.isArray(r.matches)) return { ...r,
        ...(Array.isArray(r.pages) && { pages: map(r.pages, p => ({ ...p, passage: this.page(p, str(p.passage)) })) }),
        ...(Array.isArray(r.matches) && { matches: map(r.matches, d => ({ ...d, snippet: this.doc(d, str(d.snippet)) })) }),
      };
    }
    if (["terminal_command", "terminal_verify", "sshs3_change"].includes(name)) {
      const out = { ...r };
      const brokerId = str(r.source).match(/^terminal:(.+)$/)?.[1];
      const id = brokerId ?? target?.sessionId;
      if (id && typeof r.output === "string") {
        const label = str(r.sourceLabel) || (id === target?.sessionId ? target.label : id);
        out.output = this.terminal({ id, label }, r.output, num(r.observedAt) ?? at);
      }
      if (Array.isArray(r.teamMemoryOnThisFailure)) {
        out.teamMemoryOnThisFailure = map(r.teamMemoryOnThisFailure, m => ({ ...m, text: this.memory(m, str(m.text)) }));
      }
      return out;
    }
    if (name === "sshs3_cluster_exec" && Array.isArray(r.results)) {
      // One source per node that ran the command in a terminal. A node where it did not run, where
      // it is unknown whether it ran, or whose answer is the demo's script, printed nothing to cite.
      return { ...r, results: map(r.results, node => {
        const id = str(node.source).match(/^terminal:(.+)$/)?.[1];
        return id && typeof node.output === "string" && node.exitCode !== -1
          ? { ...node, output: this.terminal({ id, label: str(node.node) || id }, node.output, at) }
          : node;
      }) };
    }
    if (name === "file_read" && typeof r.content === "string") {
      const where = str(r.source) || "file";
      return { ...r, content: this.mark(r.content, { kind: "server-reading", id: where, label: where, observedAt: num(r.observedAt) ?? at }) };
    }
    if (name === "sshs3_storage_ops") {
      if (r.operation === "read_remote_file" && typeof r.content === "string") {
        const where = `${str(r.target)}:${str(r.path)}`;
        return { ...r, content: this.mark(r.content, { kind: "server-reading", id: where, label: where, observedAt: at }) };
      }
      if (r.operation === "diff_paths" && typeof r.diff === "string") {
        const left = row(r.left), right = row(r.right);
        const where = `${str(left.target)}:${str(left.path)} and ${str(right.target)}:${str(right.path)}`;
        const d: Descriptor = { kind: "server-reading", id: where, label: `Diff of ${where}`, observedAt: at };
        // The same text under two names: one source.
        return { ...r, diff: this.mark(r.diff, d), ...(typeof r.unifiedDiff === "string" && { unifiedDiff: this.mark(r.unifiedDiff, d) }) };
      }
      // A listing is rows, not a text: it carries no reference.
      return value;
    }
    if (name === "sshs3_investigate" && Array.isArray(r.reports)) {
      return { ...r, reports: r.reports.map((item: unknown, i: number) => {
        const report = row(item);
        return report.status === "answered" && typeof report.report === "string"
          ? { ...report, report: this.mark(report.report, { kind: "investigation", id: `investigator-${i + 1}`, label: `Investigator ${i + 1}: ${str(report.question).slice(0, 140)}`, observedAt: at }) }
          : item;
      }) };
    }
    return value;
  }

  private marks(text: string): RegExpMatchArray[] {
    return [...text.matchAll(MARKER)].filter(m => m[0].startsWith("⟦" + this.nonce + ":"));
  }

  plain(text: string): string {
    return text.includes(this.nonce) ? text.replace(MARKER, m => m.startsWith("⟦" + this.nonce + ":") ? "" : m) : text;
  }

  /** Ranges point into the already retained, masked log; no second copy of its output is stored. */
  record(name: string, raw: string, kept: string, target: { sessionId: string; label: string } | undefined, at: number): StoredSourceSpan[] | undefined {
    if (!SOURCE_TOOLS.has(name)) return undefined;
    const marked = this.toolOutput(name, raw, kept, target, at);
    const spans: StoredSourceSpan[] = [];
    const starts = new Map<number, number>();
    let tags = 0;
    for (const m of this.marks(marked)) {
      const n = Number(m[1]), pos = m.index! - tags;
      tags += m[0].length;
      if (m[2] === "+") starts.set(n, pos);
      else if (starts.has(n)) {
        spans.push({ from: starts.get(n)!, to: pos, source: this.entries[n].descriptor });
        starts.delete(n);
      }
    }
    return spans;
  }

  historical(record: Pick<AgentToolRecord, "name" | "output" | "sourceSpans">): string {
    const { output } = record;
    if (!record.sourceSpans) {
      if (!SOURCE_TOOLS.has(record.name)) return output;
      // Old installations did not save the target or version that originally supplied the text.
      return this.mark(output, { kind: "terminal", id: "legacy", label: "" }, true);
    }
    let text = output;
    for (const {from,to,source} of [...record.sourceSpans].sort((a,b) => b.from-a.from)) {
      if (!source || from < 0 || from >= to || to > output.length) continue;
      text = text.slice(0,from) + this.mark(output.slice(from,to), source) + text.slice(to);
    }
    return text;
  }

  /** Project the private spans onto the exact head/tail excerpt produced by the ordinary budgeter.
   * A source entirely outside the retained ranges has no token in the provider request. */
  project(result: string, annotated: string): string {
    if (!annotated.includes(this.nonce)) return result;
    const opens = new Map<string, number>();
    const ranges: { n: string; start: number; end: number }[] = [];
    let pos = 0, plain = "";
    for (const m of this.marks(annotated)) {
      plain += annotated.slice(pos, m.index);
      pos = m.index! + m[0].length;
      if (m[2] === "+") opens.set(m[1], plain.length);
      else if (opens.has(m[1])) {
        ranges.push({ n: m[1], start: opens.get(m[1])!, end: plain.length });
        opens.delete(m[1]);
      }
    }
    plain += annotated.slice(pos);
    if (plain === result) return annotated;
    let head = 0;
    while (head < Math.min(plain.length, result.length) && plain[head] === result[head]) head++;
    const footerAt = result.lastIndexOf("\n[Full masked output (");
    const bodyEnd = footerAt < 0 ? result.length : footerAt;
    let tail = 0;
    while (tail < Math.min(plain.length-head, bodyEnd-head) && plain[plain.length-tail-1] === result[bodyEnd-tail-1]) tail++;
    let out = result;
    const inserts: { n: string; a: number; b: number }[] = [];
    for (const { n, start, end } of ranges) {
      if (start < head && end > 0) inserts.push({ n, a: start, b: Math.min(end, head) });
      if (end > plain.length-tail) inserts.push({ n, a: bodyEnd-plain.length+Math.max(start,plain.length-tail), b: bodyEnd-plain.length+end });
    }
    for (const {n,a,b} of inserts.sort((x,y) => y.a-x.a)) if (a < b) {
      out = out.slice(0,a) + `⟦${this.nonce}:${n}+⟧` + out.slice(a,b) + `⟦${this.nonce}:${n}-⟧` + out.slice(b);
    }
    return out;
  }

  toolOutput(name: string, raw: string, formatted: string, target?: { sessionId: string; label: string }, at?: number): string {
    if (!SOURCE_TOOLS.has(name)) return formatted;
    try {
      const input: unknown = JSON.parse(raw);
      const marked = this.tool(name, input, target, at);
      if (marked === input) return formatted;
      return this.project(formatted, this.clean(JSON.stringify(marked)));
    } catch { return formatted; }
  }

  /** Inspect the masked, clipped body before dispatch. Image bytes, tool schemas and model output are never scanned. */
  wire(body: string, at: number): { body: string; call: AnswerSourceCall } {
    const call: AnswerSourceCall = { id: crypto.randomUUID(), at, sources: [] };
    if (!body.includes(this.nonce)) return { body, call };
    const pieces = new Map<Source, string[]>();
    const clean = (text: string): string => {
      if (!text.includes(this.nonce)) return text;
      const marks = this.marks(text);
      for (let i = 0; i < marks.length; i++) {
        const m = marks[i], source = this.entries[Number(m[1])];
        if (!source) continue;
        const next = marks[i + 1];
        let piece: string;
        if (m[2] === "+" && next?.[1] === m[1] && next[2] === "-") {
          piece = text.slice(m.index! + m[0].length, next.index);
          i++;
        } else {
          // A budget cut through a source. Find only the surviving prefix/suffix of that field.
          const after = m[2] === "+";
          const fragment = after ? text.slice(m.index! + m[0].length, next?.index) : text.slice(0, m.index);
          piece = "";
          for (const sample of [source.text, JSON.stringify(source.text).slice(1, -1)]) {
            const limit = Math.min(sample.length, fragment.length);
            let n = 0;
            while (n < limit && (after ? sample[n] === fragment[n] : sample.at(-n-1) === fragment.at(-n-1))) n++;
            if (n > piece.length) piece = after ? fragment.slice(0,n) : fragment.slice(-n);
          }
        }
        if (!piece.trim()) continue;
        if (source.legacy) { call.untracedHistory = true; continue; }
        // Structured tool results and the JSON snapshot escape strings for their inner JSON document.
        if ((source.descriptor.kind === "terminal" || source.descriptor.kind === "server-reading" || source.descriptor.kind === "investigation") && piece.includes("\\")) try { piece = JSON.parse('"' + piece + '"') as string; } catch { /* plain display text */ }
        const retained = pieces.get(source) ?? [];
        retained.push(piece);
        pieces.set(source, retained);
      }
      return text.replace(MARKER, (marker, n: string, boundary: string) => {
        if (!marker.startsWith("⟦" + this.nonce + ":")) return marker;
        const source = this.entries[Number(n)];
        return boundary === "-" && pieces.has(source) ? ` [${source.ref}]` : "";
      });
    };
    // Markers are private to this runtime. Only server-produced source strings contain them.
    const payload = JSON.parse(body, (_key, v: unknown) => typeof v === "string" ? clean(v) : v) as Row;
    call.sources = [...pieces].map(([source, parts]) => {
      const digest = hash(parts.length === 1 ? parts[0] : JSON.stringify(parts));
      const entry: AnswerSource = { ...source.descriptor, ref: source.ref, digest };
      if (entry.kind === "server-reading") {
        const preview = maskContext([...new Set(parts)].join(" … "));
        entry.excerpt = preview.slice(0, 360);
        if (preview.length > 360 || parts.some(p => p !== source.text)) entry.excerptTruncated = true;
      }
      if (entry.kind === "terminal") {
        entry.segments = parts;
        const preview = parts.join(" … ").replace(/<\/?untrusted_data\b[^>]*>/g, "").trim();
        entry.excerpt = preview.slice(-360);
        if (preview.length > 360 || parts.length > 1) entry.excerptTruncated = true;
      }
      return entry;
    });
    return { body: JSON.stringify(payload), call };
  }
}
