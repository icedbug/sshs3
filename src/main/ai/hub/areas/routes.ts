export type AreaName = (typeof AREA_OF)[keyof typeof AREA_OF];
/** The actions a part answers. */
export type ActionsOf<N extends AreaName> = { [A in keyof typeof AREA_OF]: (typeof AREA_OF)[A] extends N ? A : never }[keyof typeof AREA_OF];
/** The requests a part answers, each with its own fields. */
export type RequestsOf<N extends AreaName> = Extract<HubRequest, { action: ActionsOf<N> }>;

/** What a part's answer is: something to send back beside the snapshot, or the snapshot itself when the case made it. */
export interface Handled {
  reply?: HubReply;
  snapshot?: HubSnapshot;
}

/** The part that answers an action, or nothing for a word that is not an action (never a key of Object's own). */
export function areaOf(action: string): AreaName | undefined {
  return Object.prototype.hasOwnProperty.call(AREA_OF, action) ? AREA_OF[action as keyof typeof AREA_OF] : undefined;
}
