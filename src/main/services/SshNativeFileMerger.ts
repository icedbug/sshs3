import { createLogger } from '../log';
const sshs3Log = createLogger('sshs3');

export type { KnownHostsConflict };

/**
 * Merge logic for the two real OpenSSH files (`~/.ssh/config` and
 * `~/.ssh/known_hosts`) that remote profile sync can optionally manage.
 * These are shared with the system's own SSH client and other tools, so —
 * unlike the JSON stores — they must never be wholesale overwritten. This
 * module is pure text manipulation with no filesystem access, so it can be
 * unit tested without risk of touching a real ~/.ssh directory; the caller
 * is responsible for reading/writing the actual files.
 */

const MANAGED_BEGIN = '# BEGIN sshs3-managed (do not edit by hand -- managed by sshs3 Remote Profile Sync)';
const MANAGED_END = '# END sshs3-managed';
// A second, purely local block (never synced, never read by the sync code) that overrides the managed
// block's identity settings for smartcard/FIDO2 hosts while their keys are unlocked in the app agent.
const AGENT_BEGIN = '# BEGIN sshs3-agent (local only -- regenerated by sshs3 while cards are unlocked, never synced)';
const AGENT_END = '# END sshs3-agent';
const TIMESTAMP_PREFIX = '# sshs3-sync-updated-at: ';

export interface ManagedSshConfigBlock {
  updatedAt: string;
  /** The Host entries etc. inside the managed block, excluding the markers and timestamp comment. */
  body: string;
}

const PATH_DIRECTIVES = new Set(['pkcs11provider', 'identityfile', 'certificatefile']);

/**
 * ssh_config splits unquoted values on whitespace, so a path like
 * `C:\Program Files\OpenSC Project\...` (typical on Windows) makes ssh abort with "extra arguments
 * at end of line" for every connection, not just inside sshs3. Quotes such a value (and uses
 * forward slashes, which Win32-OpenSSH accepts and which survive ssh_config's backslash handling
 * inside quotes) so a synced block is always parseable. Already-quoted values are left alone.
 */
function quoteSpacedPathValue(line: string): string {
  const match = /^(\s*)(\S+?)(\s*=\s*|\s+)(.+?)\s*$/.exec(line);
  if (!match) return line;
  const [, indent, key, sep, value] = match;
  if (!PATH_DIRECTIVES.has(key.toLowerCase())) return line;
  if (value.startsWith('"') || !/\s/.test(value)) return line;
  // A trailing " # comment" is not part of the path — don't swallow it into the quotes.
  if (/\s#/.test(value)) return line;
  // Backslashes only mean "path separator" for a Windows drive path (C:\...); leave anything else byte-for-byte.
  const normalized = /^[A-Za-z]:[\\/]/.test(value) ? value.replace(/\\/g, '/') : value;
  return `${indent}${key}${sep}"${normalized}"`;
}

export interface SanitizeSshConfigBodyResult {
  body: string;
  removedLines: string[];
}

/**
 * Strips any line whose directive is blocked, or not in ALLOWED_MANAGED_BLOCK_DIRECTIVES, from a managed
 * block body before it's ever written to disk. Applied only on the
 * receiving end of a sync pull (see writeManagedSshConfigBlock) — the
 * user's own locally-authored content is never touched, only content
 * arriving from the (untrusted-until-proven-otherwise) sync source.
 */
export function sanitizeSshConfigBody(body: string): SanitizeSshConfigBodyResult {
  const removedLines: string[] = [];
  const keptLines: string[] = [];

  for (const line of body.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      keptLines.push(line);
      continue;
    }
    // ssh_config directives are "Key value" or "Key=value", optionally
    // preceded by whitespace; keys are case-insensitive. OpenSSH also accepts a
    // double-quoted keyword ("ProxyCommand" cmd), so quotes are stripped before the lookup.
    const directive = trimmed.split(/[\s=]+/, 1)[0]?.replace(/["']/g, '').toLowerCase();
    if (directive && (BLOCKED_SSH_DIRECTIVES.has(directive) || !ALLOWED_MANAGED_BLOCK_DIRECTIVES.has(directive))) {
      removedLines.push(line);
      continue;
    }
    keptLines.push(quoteSpacedPathValue(line));
  }

  return { body: keptLines.join('\n'), removedLines };
}

/** Reads the sshs3-managed block out of a `~/.ssh/config` file's content, if present. */
export function parseManagedSshConfigBlock(fileContent: string): ManagedSshConfigBlock | null {
  const beginIdx = fileContent.indexOf(MANAGED_BEGIN);
  const endIdx = fileContent.indexOf(MANAGED_END);
  if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) {
    return null;
  }

  const inner = fileContent.slice(beginIdx + MANAGED_BEGIN.length, endIdx);
  const lines = inner.replace(/^\r?\n/, '').split('\n');
  let updatedAt = '';
  let bodyLines = lines;
  if (lines[0]?.startsWith(TIMESTAMP_PREFIX)) {
    updatedAt = lines[0].slice(TIMESTAMP_PREFIX.length).trim();
    bodyLines = lines.slice(1);
  }
  const body = bodyLines.join('\n').replace(/^\n+/, '').replace(/\s+$/, '');
  return { updatedAt, body };
}

/**
 * Writes (inserts or replaces) the sshs3-managed block in a `~/.ssh/config`
 * file's content. Everything outside the markers is left untouched; if no
 * managed block exists yet, one is appended at the end of the file.
 */
export function writeManagedSshConfigBlock(fileContent: string, block: ManagedSshConfigBlock): string {
  const { body: safeBody, removedLines } = sanitizeSshConfigBody(block.body);
  if (removedLines.length > 0) {
    sshs3Log.warn(`Remote Profile Sync: refused to write ${removedLines.length} disallowed ssh_config directive(s) ` +
        `synced from remote into ~/.ssh/config (would allow code execution from any future "ssh" invocation): ` +
        removedLines.map((l) => JSON.stringify(l.trim())).join(', ')
    );
  }
  const blockText = `${MANAGED_BEGIN}\n${TIMESTAMP_PREFIX}${block.updatedAt}\n${safeBody}\n${MANAGED_END}`;

  const beginIdx = fileContent.indexOf(MANAGED_BEGIN);
  const endIdx = fileContent.indexOf(MANAGED_END);
  if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) {
    if (fileContent.length === 0) {
      return `${blockText}\n`;
    }
    const separator = fileContent.endsWith('\n') ? '\n' : '\n\n';
    return `${fileContent}${separator}${blockText}\n`;
  }

  const before = fileContent.slice(0, beginIdx);
  const after = fileContent.slice(endIdx + MANAGED_END.length);
  return `${before}${blockText}${after}`;
}

/**
 * ssh_config `Host` patterns treat whitespace as a pattern separator and
 * `* ? ! [ ] ,` as glob/negation syntax, so a profile name containing any of
 * those can't be used as a literal alias — replace them rather than let one
 * profile's alias accidentally match (or fail to match) unrelated hosts.
 */
const HOST_ALIAS_UNSAFE_CHARS = /[\s*?![\],]+/g;

function sshConfigHostAlias(profile: SSHConnectionConfig): string {
  const base = oneLine(profile.name?.trim() || profile.host || profile.id).replace(HOST_ALIAS_UNSAFE_CHARS, '-');
  return base.replace(/^-+|-+$/g, '') || profile.id;
}

/** Collapses line breaks so a profile field can never smuggle an extra directive line into the config. */
const oneLine = (value: string | number): string => String(value).replace(/[\r\n]+/g, ' ');

/**
 * Builds one `Host` entry's directive lines for a single SSH profile.
 * Only connection-shape settings that have a direct, safe ssh_config
 * equivalent are emitted — secrets (password/passphrase/PIN) have no
 * ssh_config representation and are deliberately left out; native `ssh`
 * will just prompt for them interactively same as it always has.
 */
function buildSshConfigHostBlock(
  profile: SSHConnectionConfig,
  alias: string,
  aliasById: Map<string, string>
): string {
  const lines = [`Host ${alias}`, `    HostName ${oneLine(profile.host)}`];

  if (profile.port && profile.port !== 22) {
    lines.push(`    Port ${oneLine(profile.port)}`);
  }
  if (profile.username) {
    lines.push(`    User ${oneLine(profile.username)}`);
  }
  if (profile.authType === 'privateKey' && profile.privateKeyPath) {
    lines.push(`    IdentityFile ${oneLine(profile.privateKeyPath)}`);
  }
  if (profile.authType === 'smartcard' && profile.pkcs11LibPath) {
    lines.push(`    PKCS11Provider ${oneLine(profile.pkcs11LibPath)}`);
  }
  const jumpAlias = profile.proxyJumpProfileId ? aliasById.get(profile.proxyJumpProfileId) : undefined;
  if (jumpAlias) {
    // Reference the jump profile's own Host alias rather than resolving to a literal
    // user@host: this block is generated for every profile in one pass, so the alias is
    // already stable and native ssh can chain through it exactly like the app does.
    lines.push(`    ProxyJump ${jumpAlias}`);
  } else if (profile.proxyJump) {
    lines.push(`    ProxyJump ${oneLine(profile.proxyJump)}`);
  }
  if (profile.forwardAgent) {
    lines.push('    ForwardAgent yes');
  }
  if (profile.compression) {
    lines.push('    Compression yes');
  }
  if (profile.serverAliveInterval) {
    lines.push(`    ServerAliveInterval ${oneLine(profile.serverAliveInterval)}`);
  }
  if (profile.ciphers) {
    lines.push(`    Ciphers ${oneLine(profile.ciphers)}`);
  }
  if (profile.kexAlgorithms) {
    lines.push(`    KexAlgorithms ${oneLine(profile.kexAlgorithms)}`);
  }
  if (profile.macs) {
    lines.push(`    MACs ${oneLine(profile.macs)}`);
  }
  for (const [key, value] of Object.entries(profile.extraOptions ?? {})) {
    if (!key.trim() || !value.trim() || !isAllowedExtraOption(key)) continue;
    lines.push(`    ${oneLine(key)} ${oneLine(value)}`);
  }

  return lines.join('\n');
}

/** The order profiles appear in the managed block; aliases are assigned in the same order. */
function sortProfilesForConfig(profiles: SSHConnectionConfig[]): SSHConnectionConfig[] {
  return [...profiles].sort((a, b) => (a.name || a.host).localeCompare(b.name || b.host));
}

/**
 * The `Host` alias each profile gets in the managed block (sorted by name, collisions suffixed -2, -3…).
 * Exported so the local agent block can address exactly the same hosts.
 */
export function assignHostAliases(profiles: SSHConnectionConfig[]): Map<string, string> {
  const usedAliases = new Set<string>();
  const aliasById = new Map<string, string>();
  for (const profile of sortProfilesForConfig(profiles)) {
    let alias = sshConfigHostAlias(profile);
    let suffix = 2;
    while (usedAliases.has(alias)) {
      alias = `${sshConfigHostAlias(profile)}-${suffix}`;
      suffix += 1;
    }
    usedAliases.add(alias);
    aliasById.set(profile.id, alias);
  }
  return aliasById;
}

/**
 * Generates the sshs3-managed block's body from the user's saved SSH
 * profiles, so a plain `ssh <alias>` typed in any terminal (inside or
 * outside the app) picks up the same host/port/user/identity/etc. as the
 * matching profile. `extraOptions` can carry arbitrary directive names —
 * possibly merged in from a remote sync source — so the result still goes
 * through the same sanitizeSshConfigBody() pass as a synced block before
 * ever being written to disk (see writeManagedSshConfigBlock).
 *
 * `previousBlock`'s `updatedAt` is reused whenever regeneration produces the
 * same body as before, so re-generating on every profile save doesn't
 * perpetually mark this machine "ahead" in sync comparisons for a no-op.
 */
export function buildManagedSshConfigBlockFromProfiles(
  profiles: SSHConnectionConfig[],
  previousBlock: ManagedSshConfigBlock | null,
  now: string = new Date().toISOString()
): ManagedSshConfigBlock {
  const aliasById = assignHostAliases(profiles);
  const blocks = sortProfilesForConfig(profiles).map((profile) =>
    buildSshConfigHostBlock(profile, aliasById.get(profile.id)!, aliasById)
  );

  const body = blocks.join('\n\n');
  const updatedAt = previousBlock && previousBlock.body === body ? previousBlock.updatedAt : now;
  return { updatedAt, body };
}

/** One host that should use the app agent (and only these keys) while its card is unlocked. */
export interface AgentHostEntry {
  /** The profile's `Host` alias in the managed block (see assignHostAliases). */
  alias: string;
  agentSocket: string;
  /** Public key files (`.pub`) selecting the profile's keys in the agent. */
  identityFiles: string[];
}

/** Quotes a path for ssh_config; `%` is escaped because ssh expands `%d`/`%u`-style tokens in these values. */
function configPath(value: string): string {
  const one = oneLine(value).replace(/%/g, '%%').replace(/"/g, '');
  return /\s/.test(one) ? `"${one}"` : one;
}

/**
 * Body of the local agent block. First-match-wins in ssh_config, and the block sits *before* the
 * managed block, so these override its `PKCS11Provider` (which would make ssh read the card itself and
 * ask for the PIN) and make ssh use the key from the app agent instead. Fixed templates only.
 */
export function buildAgentSshConfigBody(entries: AgentHostEntry[]): string {
  return entries
    .filter((e) => e.identityFiles.length > 0)
    .map((e) =>
      [
        `Host ${e.alias}`,
        `    IdentityAgent ${configPath(e.agentSocket)}`,
        ...e.identityFiles.map((f) => `    IdentityFile ${configPath(f)}`),
        '    IdentitiesOnly yes',
        '    PKCS11Provider none',
      ].join('\n')
    )
    .join('\n\n');
}

/**
 * Inserts, replaces or removes (`body` null/empty) the local agent block in a `~/.ssh/config`'s content.
 * It goes directly before the managed block so it takes precedence; without a managed block there is
 * nothing to override and nothing is added. Everything else is left untouched.
 */
export function writeAgentSshConfigBlock(fileContent: string, body: string | null): string {
  const hasBody = !!body && body.trim().length > 0;
  const beginIdx = fileContent.indexOf(AGENT_BEGIN);
  // END is searched from BEGIN, so a stray END marker earlier in the file can't hide the block.
  const endIdx = beginIdx === -1 ? -1 : fileContent.indexOf(AGENT_END, beginIdx + AGENT_BEGIN.length);
  const exists = beginIdx !== -1 && endIdx !== -1;

  if (!hasBody) {
    if (!exists) return fileContent;
    return fileContent.slice(0, beginIdx) + fileContent.slice(endIdx + AGENT_END.length).replace(/^\n/, '');
  }

  const blockText = `${AGENT_BEGIN}\n${body}\n${AGENT_END}`;
  if (exists) {
    return fileContent.slice(0, beginIdx) + blockText + fileContent.slice(endIdx + AGENT_END.length);
  }
  const managedIdx = fileContent.indexOf(MANAGED_BEGIN);
  if (managedIdx === -1) return fileContent;
  const before = fileContent.slice(0, managedIdx);
  return `${before}${before.endsWith('\n') || before === '' ? '' : '\n'}${blockText}\n${fileContent.slice(managedIdx)}`;
}

export interface KnownHostsMergeResult {
  mergedContent: string;
  addedCount: number;
  /** Same host, different key on each side. Never auto-resolved — surface to the user. */
  conflicts: KnownHostsConflict[];
  changed: boolean;
}

interface ParsedKnownHostsLine {
  patternField: string;
  keyType: string;
  keyBase64: string;
}

function parseKnownHostsLines(content: string): ParsedKnownHostsLine[] {
  const lines: ParsedKnownHostsLine[] = [];
  for (const rawLine of content.split('\n')) {
    const trimmed = rawLine.trim();
    if (!trimmed || trimmed.startsWith('#') || trimmed.startsWith('@')) {
      // Blank/comment lines and marker lines (@cert-authority, @revoked) are
      // left alone — this merge only concerns plain host/key entries.
      continue;
    }
    const fields = trimmed.split(/\s+/);
    if (fields.length < 3) continue;
    const [patternField, keyType, keyBase64] = fields;
    lines.push({ patternField, keyType, keyBase64 });
  }
  return lines;
}

/** The comma-separated host patterns of a known_hosts line; ssh trusts the key if any of them matches. */
function patternTokens(patternField: string): string[] {
  return patternField.split(',').filter(Boolean);
}

const hasWildcard = (token: string): boolean => token.includes('*') || token.includes('?');

/** ssh matches host names case-insensitively; a hashed entry (`|1|salt|hash`) is base64 and is not a name. */
const normalizeToken = (token: string): string => (token.startsWith('|') ? token : token.toLowerCase());

/** Dot-separated parts of `text` that contain a letter or digit. */
const nameLabels = (text: string): number => text.split('.').filter((label) => /[A-Za-z0-9]/.test(label)).length;

/**
 * A wildcard that names its domain: at least two labels stay literal after the last wildcard
 * (`*.corp.example.com`, `web?.example.com`) or before the first one (`192.168.*`). `*`, `*.com`,
 * `10.*` or `*e*` would give one key trust over a whole class of hosts.
 */
function isNarrowWildcard(token: string): boolean {
  if (!hasWildcard(token)) return true;
  const first = Math.min(...[token.indexOf('*'), token.indexOf('?')].filter((i) => i >= 0));
  const last = Math.max(token.lastIndexOf('*'), token.lastIndexOf('?'));
  return nameLabels(token.slice(last + 1)) >= 2 || nameLabels(token.slice(0, first)) >= 2;
}

/**
 * A line from the remote may add trust for hosts, but not widen it to hosts it does not name: no negation
 * and no broad wildcard (see `isNarrowWildcard`). It must also look like a key.
 */
function isAcceptableRemoteLine(line: ParsedKnownHostsLine): boolean {
  const tokens = patternTokens(line.patternField);
  if (tokens.length === 0) return false;
  if (tokens.some((t) => t.startsWith('!') || !/[A-Za-z0-9]/.test(t) || !isNarrowWildcard(t))) return false;
  return /^[A-Za-z0-9@._-]+$/.test(line.keyType) && /^[A-Za-z0-9+/]+={0,2}$/.test(line.keyBase64);
}

/** ssh's pattern match: `*` any run, `?` any one character, case-insensitive. Iterative, so no regex blow-up. */
function globMatches(pattern: string, text: string): boolean {
  const p = pattern.toLowerCase();
  const t = text.toLowerCase();
  let pi = 0;
  let ti = 0;
  let starPi = -1;
  let starTi = 0;
  while (ti < t.length) {
    if (pi < p.length && (p[pi] === '?' || p[pi] === t[ti])) {
      pi++;
      ti++;
    } else if (pi < p.length && p[pi] === '*') {
      starPi = pi++;
      starTi = ti;
    } else if (starPi !== -1) {
      pi = starPi + 1;
      ti = ++starTi;
    } else {
      return false;
    }
  }
  while (pi < p.length && p[pi] === '*') pi++;
  return pi === p.length;
}

/** Two host patterns (already normalised) can both apply to one host: equal, or one is a wildcard that matches the other. */
function tokensOverlap(a: string, b: string): boolean {
  if (a === b) return true;
  if (hasWildcard(a) && globMatches(a, b)) return true;
  return hasWildcard(b) && globMatches(b, a);
}

/**
 * Merges a downloaded `~/.ssh/known_hosts` into the local file. Strictly
 * append-only: local lines are never modified or removed. A remote entry
 * for a host/key combination already present locally is skipped; a remote
 * entry for a host that exists locally under a *different* key is reported
 * as a conflict rather than applied, since that's the same signal that
 * would indicate a possible MITM if seen during a live connection. "Same
 * host" is decided per name of a comma list and through wildcards, and a
 * remote line that widens trust (negation, broad wildcard) is dropped.
 */
export function mergeKnownHosts(localContent: string, remoteContent: string): KnownHostsMergeResult {
  const localLines = parseKnownHostsLines(localContent);
  const remoteLines = parseKnownHostsLines(remoteContent);

  // Every local host token, so that a remote line is checked against each name it covers: ssh trusts a
  // key if any pattern of any line matches, so a comma list or a wildcard must not hide a clash.
  const localByToken = new Map<string, ParsedKnownHostsLine[]>();
  const localEntries: Array<{ token: string; line: ParsedKnownHostsLine }> = [];
  for (const line of localLines) {
    for (const raw of patternTokens(line.patternField)) {
      const token = normalizeToken(raw);
      const arr = localByToken.get(token) ?? [];
      arr.push(line);
      localByToken.set(token, arr);
      localEntries.push({ token, line });
    }
  }
  const localWildcards = localEntries.filter((e) => hasWildcard(e.token));
  const seenExact = new Set(localLines.map((l) => `${l.patternField} ${l.keyType} ${l.keyBase64}`));

  const clashes = (remoteLine: ParsedKnownHostsLine): ParsedKnownHostsLine | undefined => {
    const differs = (l: ParsedKnownHostsLine) => l.keyType === remoteLine.keyType && l.keyBase64 !== remoteLine.keyBase64;
    const scan = (token: string, entries: typeof localEntries) =>
      entries.find((e) => tokensOverlap(token, e.token) && differs(e.line))?.line;
    for (const raw of patternTokens(remoteLine.patternField)) {
      const token = normalizeToken(raw);
      const found = hasWildcard(token)
        ? scan(token, localEntries)
        : (localByToken.get(token) ?? []).find(differs) ?? scan(token, localWildcards);
      if (found) return found;
    }
    return undefined;
  };

  const linesToAppend: string[] = [];
  const conflicts: KnownHostsConflict[] = [];

  for (const remoteLine of remoteLines) {
    if (!isAcceptableRemoteLine(remoteLine)) continue;
    const exactKey = `${remoteLine.patternField} ${remoteLine.keyType} ${remoteLine.keyBase64}`;
    if (seenExact.has(exactKey)) continue;

    const conflicting = clashes(remoteLine);
    if (conflicting) {
      conflicts.push({
        hostPatternField: remoteLine.patternField,
        localKeyType: conflicting.keyType,
        localFingerprint: fingerprintKey(Buffer.from(conflicting.keyBase64, 'base64')),
        remoteKeyType: remoteLine.keyType,
        remoteFingerprint: fingerprintKey(Buffer.from(remoteLine.keyBase64, 'base64')),
      });
      continue;
    }

    linesToAppend.push(exactKey);
    seenExact.add(exactKey);
  }

  if (linesToAppend.length === 0) {
    return { mergedContent: localContent, addedCount: 0, conflicts, changed: false };
  }

  const needsNewline = localContent.length > 0 && !localContent.endsWith('\n');
  const mergedContent = `${localContent}${needsNewline ? '\n' : ''}${linesToAppend.join('\n')}\n`;
  return { mergedContent, addedCount: linesToAppend.length, conflicts, changed: true };
}
