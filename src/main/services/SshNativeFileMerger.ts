import {
  ALLOWED_MANAGED_BLOCK_DIRECTIVES,
  BLOCKED_SSH_DIRECTIVES,
  isAllowedExtraOption,
} from '../ssh/blockedSshDirectives';
import type { KnownHostsConflict } from '../../shared/types/sync';
