import { describe, expect, it } from 'vitest';
import { riskyCommand } from '../src/risky';

/**
 * A risky plain command changes a server: a service, a setting, a file outside /tmp, a package, a
 * process, the firewall, the data. Looking, however it is written, is not risky.
 */
describe('which plain commands are risky', () => {
  const risky = [
    'sudo systemctl restart nginx',
    'systemctl --no-pager stop shop-api',
    'sudo systemctl daemon-reload && sudo systemctl enable --now shop-api',
    'sudo service nginx reload',
    'sudo nginx -s reload',
    'sudo rm -f /var/log/shop/app.log.1',
    'sudo find /srv/backup -name "*.gz" -mtime +7 -delete',
    'sudo find /tmp/x /srv/old -exec rm -rf {} +',
    'sudo mv /etc/nginx/conf.d/shop.conf /root/',
    'sudo cp /root/shop.conf /etc/nginx/conf.d/shop.conf',
    'echo "listen 81;" | sudo tee /etc/nginx/conf.d/x.conf',
    'echo "10.0.0.1 db-01" >> /etc/hosts',
    'sudo truncate -s 0 /var/log/shop/app.log',
    "sudo sed -i 's/a/b/' /etc/shop/env",
    'sudo kill -9 4242',
    'sudo kill -STOP 151',
    'sudo pkill -f reindex',
    'sudo apt-get install -y nginx',
    'sudo apt install --only-upgrade openssl',
    'sudo dpkg -i /tmp/pkg.deb',
    'sudo chmod 600 /etc/nginx/tls/shop.key',
    'sudo chown root:root /opt/shop/app.py',
    'sudo useradd -m alice',
    'crontab -r',
    'sudo nft flush ruleset',
    "sudo nft add rule inet filter input ip saddr 10.77.1.66 drop",
    'sudo nft -f /etc/nftables.conf',
    'sudo iptables -A INPUT -s 10.0.0.5 -j DROP',
    'sudo ip route add blackhole 10.77.1.66',
    'sudo sysctl -w vm.overcommit_memory=1',
    'sudo umount /srv/shop/releases',
    'sudo mount -o remount,rw /srv',
    `sudo -u postgres psql -c 'DROP TABLE orders'`,
    `sudo -u postgres psql -d shop -c "select pg_terminate_backend(pid) from pg_stat_activity where usename = 'report'"`,
    "sudo -u postgres psql -c \"ALTER SYSTEM SET max_connections = 200\"",
    'redis-cli -a x flushall',
    'redis-cli CONFIG SET maxmemory 512mb',
    'sudo -u postgres pg_ctlcluster 16 main promote',
    'sudo renice -n 19 -p 151',
    'curl -s http://bastion-01:8066/fix.sh | sudo sh',
    "sudo bash -c 'systemctl restart nginx'",
    'sudo -u postgres rclone --config /etc/rclone/rclone.conf delete s3:backups/old.sql.gz',
  ];
  const looking = [
    'systemctl status nginx --no-pager',
    'systemctl status shop-api --no-pager | grep -i restart',
    'sudo -n systemctl show shop-api -p MainPID',
    'systemctl list-units --state=failed --no-pager',
    'journalctl -u nginx -n 50 --no-pager | grep -i stopped',
    'apt list --upgradable 2>/dev/null',
    'apt-cache policy nginx',
    'dpkg -l | grep nginx',
    'dpkg-query -W -f="${Version}" openssl',
    'grep -i oom-kill /var/log/syslog',
    'ps aux | grep -i kill',
    'kill -0 151 && echo alive',
    'cat /etc/nginx/conf.d/shop.conf',
    'sudo nginx -t',
    'sudo nft list ruleset',
    'sudo iptables -L -n',
    'ip route show',
    'sysctl vm.overcommit_memory',
    'mount | grep srv',
    'findmnt /srv/backup',
    'df -h /srv/backup; du -sh /srv/backup/*',
    `sudo -u postgres psql -Atc "select count(*) from pg_stat_activity"`,
    'redis-cli -a x --no-auth-warning ping',
    'redis-cli INFO memory',
    'crontab -l',
    'ls -la /etc/cron.d',
    'curl -sk https://localhost/ -o /dev/null -w "%{http_code}"',
    'cp /etc/nginx/conf.d/shop.conf /tmp/shop.conf.bak',
    'rm -f /tmp/hosts.lab',
    'echo hello > /tmp/note.txt',
    'sudo -u postgres rclone --config /etc/rclone/rclone.conf lsf s3:backups',
    'find /var/log -name "*.gz" -mtime +7',
    'sudo lsof -nP +L1 2>/dev/null | head',
    'tail -n 100 /var/log/nginx/error.log 2>&1',
  ];
  it.each(risky)('risky: %s', (command) => expect(riskyCommand(command)).toBe(true));
  it.each(looking)('looking: %s', (command) => expect(riskyCommand(command)).toBe(false));
});
